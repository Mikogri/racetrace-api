begin;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('round-images', 'round-images', true, 10485760, array['image/png'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists public_read_round_images_storage on storage.objects;
create policy public_read_round_images_storage
on storage.objects
for select
to anon, authenticated
using (bucket_id = 'round-images');

create table if not exists public.venue_images (
  id bigint generated by default as identity primary key,
  venue_key text not null unique,
  storage_path text not null unique,
  content_type text not null default 'image/png',
  file_name text,
  alt_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint venue_images_venue_key_not_blank check (btrim(venue_key) <> ''),
  constraint venue_images_storage_path_not_blank check (btrim(storage_path) <> ''),
  constraint venue_images_content_type_png_check check (content_type = 'image/png')
);

drop trigger if exists set_venue_images_updated_at on public.venue_images;
create trigger set_venue_images_updated_at
before update on public.venue_images
for each row execute function public.set_updated_at();

alter table public.venue_images enable row level security;
grant select on public.venue_images to anon, authenticated;
revoke insert, update, delete, truncate, references, trigger
on public.venue_images from anon, authenticated;

drop policy if exists public_read_venue_images on public.venue_images;
create policy public_read_venue_images
on public.venue_images
for select
to anon, authenticated
using (true);

alter table public.tracks
  add column if not exists venue_image_id bigint;

alter table public.tracks
  drop constraint if exists tracks_venue_image_id_fkey;

alter table public.tracks
  add constraint tracks_venue_image_id_fkey
  foreign key (venue_image_id) references public.venue_images(id)
  on update cascade on delete set null;

create index if not exists tracks_venue_image_id_idx
  on public.tracks (venue_image_id);

alter table public.round_images
  add column if not exists storage_path text;

alter table public.round_images
  alter column image_data drop not null;

alter table public.round_images
  drop constraint if exists round_images_source_check;

alter table public.round_images
  add constraint round_images_source_check
  check (num_nonnulls(image_data, storage_path) = 1);

alter table public.round_images
  drop constraint if exists round_images_storage_path_not_blank;

alter table public.round_images
  add constraint round_images_storage_path_not_blank
  check (storage_path is null or btrim(storage_path) <> '');

create index if not exists round_images_storage_path_idx
  on public.round_images (storage_path)
  where storage_path is not null;

commit;
